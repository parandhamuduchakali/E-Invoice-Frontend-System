#!/usr/bin/env node
/**
 * Generates src/api/schema.d.ts from the backend's OpenAPI contract.
 *
 *   npm run gen:api                       # reads ../E-Invoice-Backend-system/docs/openapi.json
 *   npm run gen:api -- path/to/openapi.json
 *   npm run gen:api -- http://127.0.0.1:8000/openapi.json
 *
 * The backend writes docs/openapi.json with `python docs/generate.py`, and its
 * CI fails if that file is not what the code produces. This script turns it
 * into TypeScript, and src/api/contract.ts holds compile-time assertions that
 * the hand-written types in src/api/types.ts still agree with it — so a
 * backend field rename fails `tsc` here rather than surfacing as `undefined`
 * in a rendered invoice.
 *
 * The generated file is committed. CI regenerates it and fails on a diff, so
 * "the backend changed and nobody regenerated" is caught too.
 */

import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import openapiTS, { astToString } from "openapi-typescript";

const DEFAULT_SOURCE = "../E-Invoice-Backend-system/docs/openapi.json";
const OUTPUT = "src/api/schema.d.ts";

const source = process.argv[2] ?? DEFAULT_SOURCE;

async function loadSchema(location) {
  if (/^https?:\/\//.test(location)) {
    const response = await fetch(location);
    if (!response.ok) throw new Error(`${location} answered ${response.status}`);
    return response.json();
  }
  return JSON.parse(await readFile(resolve(location), "utf8"));
}

const schema = await loadSchema(source);
const ast = await openapiTS(schema, {
  // Nullable fields become `T | null`, matching how the pages test for absence.
  defaultNonNullable: false,
});

const header = `/* eslint-disable */
/**
 * GENERATED by scripts/gen-api-types.mjs from the backend's OpenAPI schema.
 * Do not edit: run \`npm run gen:api\`. See src/api/contract.ts for how the
 * hand-written types in src/api/types.ts are checked against this file.
 *
 * Source: ${source}
 * Backend version: ${schema.info?.version ?? "unknown"}
 */
`;

await writeFile(OUTPUT, header + astToString(ast), "utf8");
console.log(`wrote ${OUTPUT} from ${source} (${Object.keys(schema.components?.schemas ?? {}).length} schemas)`);
